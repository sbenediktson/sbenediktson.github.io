'use strict';

const { esc } = require('./html');
const { link, absoluteUrl } = require('./config');
const { pageTitle } = require('./episodes');
const { formatLongDate } = require('./dates');

const episodeUrl = (slug) => `/episodes/${slug}/`;
const musicianUrl = (slug) => `/musicians/${slug}/`;
const watchUrl = (id) => `https://www.youtube.com/watch?v=${id}`;

const formatDate = formatLongDate;

function trim160(s) {
  if (s.length <= 160) return s;
  const cut = s.slice(0, 159).replace(/\s+\S*$/, '').replace(/[\s,;:.-]+$/, '');
  return cut + '…';
}

function describeEpisode(ep) {
  const names = ep.artists.map((a) => a.name).filter(Boolean);
  const date = formatDate(ep.streamDate);
  if (ep.number === null) {
    // Lead with the (unique) page title; add the date, then the lineup, only as space allows.
    let s = `Watch ${pageTitle(ep)}, a full-length Emmet Cohen concert`;
    const fit = (extra) => { if ((s + extra + '.').length <= 160) s += extra; };
    if (date) fit(`, streamed ${date}`);
    for (let k = names.length; k > 0; k--) {
      const before = s;
      fit(` with ${names.slice(0, k).join(', ')}`);
      if (s !== before) break;
    }
    return trim160(s + '.');
  }
  let s = `Watch Vol. ${ep.number} of Live From Emmet's Place`;
  if (names.length) s += ` featuring ${names.join(', ')}`;
  if (date) s += `, streamed ${date}`;
  if (ep.location) s += ` from ${ep.location}`;
  s += names.length ? '.' : '. Live jazz, full video and setlist.';
  return trim160(s);
}

function layout({ title, description, canonicalPath, body, robots }) {
  const url = absoluteUrl(canonicalPath);
  return `<!DOCTYPE html>
<!-- generated by build-site.js -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
${robots ? '<meta name="robots" content="noindex,nofollow">\n' : ''}<link rel="canonical" href="${esc(url)}">
<meta property="og:type" content="website">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:url" content="${esc(url)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Bebas+Neue&display=swap" rel="stylesheet">
<link rel="stylesheet" href="${esc(link('/page.css'))}">
</head>
<body>
<header class="site-header"><a href="${esc(link('/'))}">Emmet's Place</a></header>
<main>
${body}
</main>
</body>
</html>
`;
}

function renderEpisodePage(ep, ctx) {
  const title = pageTitle(ep);
  const musicianSlugs = ctx.musicianSlugs || {};
  const date = formatDate(ep.streamDate);
  const meta = [date, ep.location].filter(Boolean).map(esc).join(' &middot; ');
  const parts = [`<h1>${esc(title)}</h1>`];
  if (meta) parts.push(`<p class="meta">${meta}</p>`);
  parts.push(
    `<div class="video"><iframe src="https://www.youtube.com/embed/${esc(ep.id)}" title="${esc(title)}" allow="accelerometer; encrypted-media; picture-in-picture" allowfullscreen loading="lazy"></iframe></div>`,
    `<p><a href="${esc(watchUrl(ep.id))}">Watch on YouTube</a></p>`
  );
  if (ep.artists.length) {
    const items = ep.artists.map((a) => {
      const slug = musicianSlugs[a.name];
      const name = slug ? `<a href="${esc(link(musicianUrl(slug)))}">${esc(a.name)}</a>` : esc(a.name);
      return `<li>${name}${a.instrument ? ` <span class="role">${esc(a.instrument)}</span>` : ''}</li>`;
    });
    parts.push(`<h2>Lineup</h2>\n<ul>\n${items.join('\n')}\n</ul>`);
  }
  if (ep.songs.length) {
    const items = ep.songs.map((s) => `<li><a href="${esc(`${watchUrl(ep.id)}&t=${Math.floor(Number(s.start) || 0)}`)}">${esc(s.title)}</a></li>`);
    parts.push(`<h2>Setlist</h2>\n<ol>\n${items.join('\n')}\n</ol>`);
  }
  if (ep.restreams.length) {
    const items = ep.restreams.map((r) => `<li><a href="${esc(watchUrl(r.id))}">${esc(r.title)}</a></li>`);
    parts.push(`<h2>Also on YouTube</h2>\n<ul>\n${items.join('\n')}\n</ul>`);
  }
  const nav = [];
  for (const [rel, e] of [['Previous', ctx.prev], ['Next', ctx.next]]) {
    const slug = e && ctx.slugs[e.id];
    if (slug) nav.push(`<a href="${esc(link(episodeUrl(slug)))}">${rel}: ${esc(pageTitle(e))}</a>`);
  }
  if (nav.length) parts.push(`<nav class="pager">${nav.join('\n')}</nav>`);
  parts.push(`<p><a href="${esc(link('/'))}">All episodes</a></p>`);
  return layout({ title, description: describeEpisode(ep), canonicalPath: episodeUrl(ctx.slugs[ep.id]), body: parts.join('\n') });
}

function episodeList(episodes, slugs) {
  const items = episodes
    .filter((e) => slugs[e.id])
    .map((e) => {
      const date = formatDate(e.streamDate);
      return `<li><a href="${esc(link(episodeUrl(slugs[e.id])))}">${esc(pageTitle(e))}</a>${date ? ` <span class="role">${esc(date)}</span>` : ''}</li>`;
    });
  return `<ul>\n${items.join('\n')}\n</ul>`;
}

function renderMusicianPage(m, ctx) {
  const n = m.appearances.length;
  const title = `${m.name} - Live From Emmet's Place`;
  const instruments = m.instruments.length ? ` (${m.instruments.join(', ')})` : '';
  const description = trim160(`${m.name}${instruments} appearances on Live From Emmet's Place: ${n} episode${n === 1 ? '' : 's'} of live jazz with full video and setlists.`);
  const body = [
    `<h1>${esc(m.name)}</h1>`,
    m.instruments.length ? `<p class="meta">${esc(m.instruments.join(', '))}</p>` : '',
    `<h2>Appearances</h2>`,
    episodeList(m.appearances, ctx.slugs),
    `<p><a href="${esc(link('/'))}">All episodes</a></p>`,
  ].filter(Boolean).join('\n');
  return layout({ title, description, canonicalPath: musicianUrl(ctx.musicianSlugs[m.name]), body });
}

function renderWriterPage(w, episodes, ctx) {
  const ids = new Set(w.episodeIds);
  const title = `${w.name} - Emmet's Place`;
  const body = [
    `<h1>${esc(w.name)}</h1>`,
    w.bio ? `<p>${esc(w.bio)}</p>` : '',
    '<h2>Episodes</h2>',
    episodeList(episodes.filter((e) => ids.has(e.id)), ctx.slugs),
  ].filter(Boolean).join('\n');
  return layout({ title, description: `Episodes of Live From Emmet's Place by ${w.name}.`, canonicalPath: `/writers/${w.slug}/`, body, robots: true });
}

module.exports = { renderEpisodePage, renderMusicianPage, renderWriterPage, episodeUrl, musicianUrl, link, absoluteUrl };
