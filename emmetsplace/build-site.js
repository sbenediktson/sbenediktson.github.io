'use strict';

const fs = require('fs');
const path = require('path');
const { setConfig, resetConfig, absoluteUrl } = require('./site/config');
const { selectEpisodes } = require('./site/episodes');
const { episodeSlugBase, slugify, allocateSlugs } = require('./site/slugs');
const { collectMusicians, MUSICIAN_ALIASES } = require('./site/musicians');
const { renderEpisodePage, renderMusicianPage, renderWriterPage, episodeUrl, musicianUrl } = require('./site/pages');
const { renderCards, replaceBetweenMarkers } = require('./site/home');
const { renderSitemap, renderLlmsTxt, dateOf } = require('./site/feeds');

const GENERATED_MARKER = '<!-- generated by build-site.js -->';
const PAGE_DIRS = ['episodes', 'musicians', 'writers'];

function readJson(file, what) {
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch (e) { throw new Error(`Cannot read ${what}: ${e.message}`); }
  try { return JSON.parse(text); } catch (e) { throw new Error(`Invalid JSON in ${what}: ${e.message}`); }
}

function readPinned(root) {
  const file = path.join(root, 'slugs.json');
  if (!fs.existsSync(file)) return { episodes: {}, musicians: {} };
  const j = readJson(file, 'slugs.json');
  return { episodes: (j && j.episodes) || {}, musicians: (j && j.musicians) || {} };
}

function readWriters(root) {
  const file = path.join(root, 'content', 'writers.json');
  if (!fs.existsSync(file)) return [];
  const list = readJson(file, 'content/writers.json');
  if (!Array.isArray(list)) throw new Error('content/writers.json must be an array');
  const seen = new Set();
  for (const w of list) {
    if (!w || typeof w.name !== 'string' || !SLUG_RE.test(w.slug || '') || !Array.isArray(w.episodeIds)) {
      throw new Error(`Invalid writer entry: ${JSON.stringify(w)}`);
    }
    if (seen.has(w.slug)) throw new Error(`Duplicate writer slug ${JSON.stringify(w.slug)} in content/writers.json`);
    seen.add(w.slug);
  }
  return list;
}

const SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

function requireSlugs(items, map, what) {
  for (const key of items) if (!map[key]) throw new Error(`No slug allocated for ${what} ${key}`);
  const seen = new Map();
  for (const [key, slug] of Object.entries(map)) {
    if (typeof slug !== 'string' || !SLUG_RE.test(slug)) throw new Error(`Invalid slug for ${what} ${key}: ${JSON.stringify(slug)}`);
    if (seen.has(slug)) throw new Error(`Duplicate slug ${JSON.stringify(slug)} for ${what} ${seen.get(slug)} and ${key}`);
    seen.set(slug, key);
  }
}

function readConfig(root) {
  const file = path.join(root, 'site.config.json');
  if (!fs.existsSync(file)) return {};
  return readJson(file, 'site.config.json');
}

function buildSite({ root }) {
  resetConfig();
  setConfig(readConfig(root));
  const videos = readJson(path.join(root, 'videos.json'), 'videos.json');
  if (!videos || typeof videos.data !== 'object' || videos.data === null) throw new Error('videos.json has no "data" object');
  const episodes = selectEpisodes(videos.data);
  if (!episodes.length) throw new Error('videos.json contains no episodes');

  const musicians = collectMusicians(episodes, MUSICIAN_ALIASES);
  const pinned = readPinned(root);
  const slugs = {
    episodes: allocateSlugs(episodes.map((e) => ({ key: e.id, base: episodeSlugBase(e) })), pinned.episodes),
    musicians: allocateSlugs(musicians.map((m) => ({ key: m.name, base: slugify(m.name) })), pinned.musicians),
  };
  requireSlugs(episodes.map((e) => e.id), slugs.episodes, 'episode');
  requireSlugs(musicians.map((m) => m.name), slugs.musicians, 'musician');

  const files = new Map();
  const baseCtx = { slugs: slugs.episodes, musicianSlugs: slugs.musicians };

  const home = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const intro = fs.readFileSync(path.join(root, 'content', 'home-intro.html'), 'utf8');
  files.set('index.html', replaceBetweenMarkers(replaceBetweenMarkers(home, 'intro', intro), 'cards', renderCards(episodes, slugs.episodes)));

  // episodes are newest first: "Previous" is the next-older episode, "Next" the next-newer.
  episodes.forEach((ep, i) => {
    files.set(`episodes/${slugs.episodes[ep.id]}/index.html`, renderEpisodePage(ep, { ...baseCtx, prev: episodes[i + 1], next: episodes[i - 1] }));
  });
  for (const m of musicians) files.set(`musicians/${slugs.musicians[m.name]}/index.html`, renderMusicianPage(m, baseCtx));
  for (const w of readWriters(root)) files.set(`writers/${w.slug}/index.html`, renderWriterPage(w, episodes, baseCtx));

  for (const k of files.keys()) {
    if (k.includes('..') || k.startsWith('/') || k.includes('\\')) throw new Error(`Unsafe output path: ${k}`);
  }

  const newest = (list) => list.map(dateOf).filter(Boolean).sort().pop();
  const entry = (loc, lastmod) => ({ loc: absoluteUrl(loc), ...(lastmod ? { lastmod } : {}) });
  files.set('sitemap.xml', renderSitemap([
    entry('/'),
    ...episodes.map((e) => entry(episodeUrl(slugs.episodes[e.id]), dateOf(e))),
    ...musicians.map((m) => entry(musicianUrl(slugs.musicians[m.name]), newest(m.appearances))),
  ]));
  files.set('llms.txt', renderLlmsTxt(episodes, musicians, slugs));
  files.set('slugs.json', JSON.stringify(slugs, null, 2) + '\n');
  return { files };
}

function writeSite(root, files) {
  for (const [rel, content] of files) {
    const file = path.join(root, ...rel.split('/'));
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  for (const dir of PAGE_DIRS) {
    const base = path.join(root, dir);
    if (!fs.existsSync(base)) continue;
    for (const entry of fs.readdirSync(base, { withFileTypes: true })) {
      if (!entry.isDirectory() || files.has(`${dir}/${entry.name}/index.html`)) continue;
      const index = path.join(base, entry.name, 'index.html');
      if (fs.existsSync(index) && fs.readFileSync(index, 'utf8').includes(GENERATED_MARKER)) {
        fs.rmSync(path.join(base, entry.name), { recursive: true, force: true });
      }
    }
  }
}

function main(argv) {
  const i = argv.indexOf('--root');
  const root = path.resolve(i >= 0 && argv[i + 1] ? argv[i + 1] : __dirname);
  try {
    writeSite(root, buildSite({ root }).files);
  } catch (e) {
    console.error(`build-site: ${e.message}`);
    process.exit(1);
  }
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { buildSite, writeSite, GENERATED_MARKER };
